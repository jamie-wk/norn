import { readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { generate } from '../src/index.ts';
import { copyFixture, fixture, removeDir } from './helpers.ts';

const app = fixture('app');
const GENERATED = [
  '.norn/activities.ts',
  '.norn/container.ts',
  '.norn/contracts.ts',
  '.norn/registry.ts',
  '.norn/schedules.json',
  '.norn/search-attributes.json',
  '.norn/workflows.ts',
  'norn.lock.json',
  'shared/contracts.ts',
];

describe('norn gen on the fixture app', () => {
  it('generates every file without errors', async () => {
    const result = await generate({ cwd: app, write: false });
    expect(result.errors).toEqual([]);
    expect(Object.keys(result.files).sort()).toEqual(GENERATED);
    expect(result.written).toEqual([]);
  });

  it.each(GENERATED)('matches the snapshot of %s', async (file) => {
    const { files } = await generate({ cwd: app, write: false });
    await expect(files[file]).toMatchFileSnapshot(join(app, 'expected', file));
  });

  it('starts every TypeScript file with the generated header', async () => {
    const { files } = await generate({ cwd: app, write: false });
    const ts = Object.entries(files).filter(([file]) => file.endsWith('.ts'));
    expect(ts).toHaveLength(6);
    expect(ts.filter(([, content]) => !content.startsWith('// Generated by norn gen. Do not edit.\n')).map(([file]) => file)).toEqual([]);
  });

  it('is deterministic', async () => {
    const a = await generate({ cwd: app, write: false });
    const b = await generate({ cwd: app, write: false });
    expect(b.files).toEqual(a.files);
  });

  it('finds norn.config.ts from a subdirectory', async () => {
    const fromRoot = await generate({ cwd: app, write: false });
    const fromSub = await generate({ cwd: join(app, 'src', 'workflows'), write: false });
    expect(fromSub.files).toEqual(fromRoot.files);
  });

  it('exports workflows under their type names and imports only workflow files', async () => {
    const { files } = await generate({ cwd: app, write: false });
    const workflows = files['.norn/workflows.ts']!;
    expect(workflows).toContain("import { CartWorkflow as ShoppingCart$ } from '../src/workflows/cart.js';");
    expect(workflows).toContain('export const ShoppingCart = implement(ShoppingCart$');
    expect(workflows).not.toMatch(/activities|services/);
    expect(files['.norn/activities.ts']).not.toMatch(/^import \{ (?!defineActivities)/m);
    expect(files['.norn/contracts.ts']).not.toMatch(/^import \{ (?!contract)/m);
  });

  it('records schedules, search attributes and the lock', async () => {
    const { files } = await generate({ cwd: app, write: false });
    expect(JSON.parse(files['.norn/schedules.json']!)).toEqual([
      {
        id: 'nightly-report',
        workflowType: 'ReportWorkflow',
        taskQueue: 'reports',
        cron: ['0 2 * * *'],
        input: { kind: 'daily' },
        overlap: 'buffer-one',
        timeZone: 'America/New_York',
        note: 'Nightly totals',
      },
      {
        id: 'report-workflow',
        workflowType: 'ReportWorkflow',
        taskQueue: 'reports',
        cron: ['0 9 * * 1', '0 9 * * 4'],
        input: { kind: 'weekly' },
        pauseOnFailure: true,
        paused: true,
      },
    ]);
    expect(JSON.parse(files['.norn/search-attributes.json']!)).toEqual({ CartSize: 'int', CustomerId: 'keyword', OrderStatus: 'keyword' });
    expect(JSON.parse(files['norn.lock.json']!)).toEqual({
      version: 1,
      workflows: {
        OrderWorkflow: { taskQueue: 'orders', signals: ['cancel', 'complete', 'transfer-event'], queries: ['status'], updates: ['add-item'] },
        ReportWorkflow: { taskQueue: 'reports', signals: [], queries: [], updates: [] },
        ShoppingCart: { taskQueue: 'carts', signals: ['checkout', 'pause', 'resume'], queries: ['contents', 'isPaused'], updates: ['add'] },
      },
      activities: ['buildReport', 'inventory.release', 'inventory.reserve', 'payments.charge', 'payments.refund-charge'],
    });
  });
});

describe('writing and --check', () => {
  const dirs: string[] = [];
  afterAll(() => dirs.forEach(removeDir));

  it('writes files, rewrites only what changed, and reports stale files in check mode', async () => {
    const dir = copyFixture('app');
    dirs.push(dir);
    rmSync(join(dir, 'expected'), { recursive: true, force: true });

    const first = await generate({ cwd: dir });
    expect(first.errors).toEqual([]);
    expect(first.written.sort()).toEqual(GENERATED);
    expect(readFileSync(join(dir, '.norn/workflows.ts'), 'utf8')).toBe(first.files['.norn/workflows.ts']);

    const second = await generate({ cwd: dir });
    expect(second.written).toEqual([]);
    expect((await generate({ cwd: dir, check: true })).stale).toEqual([]);

    const order = join(dir, 'src/workflows/order.ts');
    writeFileSync(order, readFileSync(order, 'utf8').replace("@Signal() complete()", "@Signal('finish') complete()"));
    rmSync(join(dir, '.norn/schedules.json'));
    const before = readFileSync(join(dir, '.norn/contracts.ts'), 'utf8');

    const check = await generate({ cwd: dir, check: true, acceptRename: true });
    expect(check.errors).toEqual([]);
    expect(check.stale.sort()).toEqual(['.norn/contracts.ts', '.norn/schedules.json', 'norn.lock.json', 'shared/contracts.ts']);
    expect(check.written).toEqual([]);
    expect(readFileSync(join(dir, '.norn/contracts.ts'), 'utf8')).toBe(before);
    expect(existsSync(join(dir, '.norn/schedules.json'))).toBe(false);

    const accepted = await generate({ cwd: dir, acceptRename: true });
    expect(accepted.written.sort()).toEqual(check.stale.sort());
    expect(readFileSync(join(dir, '.norn/contracts.ts'), 'utf8')).toContain("complete: 'finish'");
  });
});
