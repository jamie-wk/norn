import { dirname, relative } from 'node:path';
import { compare, type ActivitiesModel, type Analysis, type DependencyRef, type ScheduleModel, type WorkflowModel } from './analyze.js';
import type { Literal } from './literal.js';

export const HEADER = '// Generated by norn gen. Do not edit.\n';
const WIDTH = 110;
const IDENT = /^[A-Za-z_$][\w$]*$/;

/** A value printed as source code verbatim, such as an identifier. */
export class Code {
  readonly text: string;
  constructor(text: string) {
    this.text = text;
  }
}

export type Printable = Literal | Code | undefined | readonly Printable[] | { readonly [key: string]: Printable };

export function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')}'`;
}

const key = (k: string) => (IDENT.test(k) ? k : quote(k));

function entries(value: { readonly [key: string]: Printable }): Array<[string, Printable]> {
  return Object.entries(value).filter(([, v]) => v !== undefined);
}

function inline(value: Printable): string {
  if (value instanceof Code) return value.text;
  if (value === null) return 'null';
  if (typeof value === 'string') return quote(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return `[${value.map(inline).join(', ')}]`;
  const list = entries(value as { [key: string]: Printable });
  return list.length === 0 ? '{}' : `{ ${list.map(([k, v]) => `${key(k)}: ${inline(v)}`).join(', ')} }`;
}

/**
 * Prints a value as TypeScript: on one line when it fits, otherwise one entry per line.
 * `column` is where the value starts on its line; `forceBreak` breaks the outermost level.
 */
export function print(value: Printable, indent = 0, column = indent * 2, forceBreak = false): string {
  const flat = inline(value);
  const isList = Array.isArray(value);
  const isObj = !isList && typeof value === 'object' && value !== null && !(value instanceof Code);
  if ((!forceBreak && column + flat.length <= WIDTH) || (!isList && !isObj)) return flat;
  const pad = '  '.repeat(indent + 1);
  if (isList) {
    const items = value as readonly Printable[];
    if (items.length === 0) return '[]';
    return `[\n${items.map((v) => `${pad}${print(v, indent + 1)},`).join('\n')}\n${'  '.repeat(indent)}]`;
  }
  const list = entries(value as { [key: string]: Printable });
  if (list.length === 0) return '{}';
  return `{\n${list.map(([k, v]) => `${pad}${key(k)}: ${print(v, indent + 1, pad.length + key(k).length + 2)},`).join('\n')}\n${'  '.repeat(indent)}}`;
}

/** The relative import specifier from a generated file's directory to a source file. */
export function importPath(fromDir: string, toFile: string, extension: '.js' | '.ts'): string {
  let rel = relative(fromDir, toFile).replaceAll('\\', '/');
  if (!/^\.\.?\//.test(rel)) rel = `./${rel}`;
  return rel.replace(/\.([cm]?)tsx?$/, (_m, flavor: string) => (extension === '.ts' ? `.${flavor}ts` : `.${flavor}js`));
}

interface ImportSpec {
  name: string;
  alias?: string;
}

/** Collects imports and prints them grouped per module, packages first. */
class Imports {
  private readonly modules = new Map<string, { typeOnly: boolean; specs: Map<string, ImportSpec> }>();

  add(specifier: string, name: string, alias?: string, typeOnly = false): void {
    let mod = this.modules.get(specifier);
    if (!mod) {
      mod = { typeOnly, specs: new Map() };
      this.modules.set(specifier, mod);
    }
    const id = `${name} as ${alias ?? name}`;
    mod.specs.set(id, { name, ...(alias && alias !== name ? { alias } : {}) });
  }

  print(): string {
    const order = (s: string) => (s.startsWith('.') ? 1 : 0);
    return [...this.modules]
      .sort(([a], [b]) => order(a) - order(b) || compare(a, b))
      .map(([specifier, { typeOnly, specs }]) => {
        const names = [...specs.values()]
          .sort((a, b) => compare(a.name, b.name) || compare(a.alias ?? '', b.alias ?? ''))
          .map((s) => (s.alias ? `${s.name} as ${s.alias}` : s.name))
          .join(', ');
        return `import${typeOnly ? ' type' : ''} { ${names} } from ${quote(specifier)};`;
      })
      .join('\n');
  }
}

function file(...sections: string[]): string {
  return `${HEADER}\n${sections.filter((s) => s !== '').join('\n\n')}\n`;
}

export interface EmitOptions {
  outDir: string;
  importExtension: '.js' | '.ts';
  /** Absolute path of the providers module. */
  providers: string | undefined;
}

const byName = <T extends { name: string }>(list: readonly T[]) => list.toSorted((a, b) => compare(a.name, b.name));
const byClass = <T extends { className: string; file: string }>(list: readonly T[]) =>
  list.toSorted((a, b) => compare(a.className, b.className) || compare(a.file, b.file));

export function emitWorkflows(analysis: Analysis, options: EmitOptions): string {
  const workflows = byName(analysis.workflows);
  if (workflows.length === 0) return file('export {};');
  const imports = new Imports();
  imports.add('@norn-ts/workflow', 'implement');
  const exports = workflows.map((wf) => {
    imports.add(importPath(options.outDir, wf.file, options.importExtension), wf.exportName, `${wf.name}$`);
    const descriptions = Object.keys(wf.descriptions).length > 0 ? { descriptions: wf.descriptions } : undefined;
    const prefix = `export const ${wf.name} = implement(${wf.name}$`;
    return descriptions ? `${prefix}, ${print(descriptions, 0, prefix.length + 2)});` : `${prefix});`;
  });
  return file(imports.print(), exports.join('\n'));
}

export function emitActivities(analysis: Analysis, options: EmitOptions): string {
  const classes = byClass(analysis.activities);
  if (classes.length === 0) return file('export {};');
  const imports = new Imports();
  imports.add('@norn-ts/workflow', 'defineActivities');
  const blocks = classes.map((cls: ActivitiesModel) => {
    imports.add(importPath(options.outDir, cls.file, options.importExtension), cls.exportName, `${cls.className}$`, true);
    const methods = Object.fromEntries(cls.methods.map((m) => [m.method, m.options]));
    return `export const ${cls.className} = defineActivities<${cls.className}$>()(${print({ prefix: cls.prefix, methods }, 0, 0, true)});`;
  });
  return file(imports.print(), blocks.join('\n\n'));
}

export function contractDefinition(wf: WorkflowModel): Printable {
  const handlers = (list: WorkflowModel['signals']) => (list.length > 0 ? Object.fromEntries(list.map((h) => [h.method, h.name])) : undefined);
  const sa = Object.keys(wf.searchAttributes).sort();
  return {
    name: wf.name,
    taskQueue: wf.taskQueue,
    id: wf.id,
    signals: handlers(wf.signals),
    queries: handlers(wf.queries),
    updates: handlers(wf.updates),
    searchAttributes: sa.length > 0 ? Object.fromEntries(sa.map((k) => [k, wf.searchAttributes[k]!])) : undefined,
  };
}

/** Contracts for API code. `targetFile` is where the file is written; imports are relative to it. */
export function emitContracts(analysis: Analysis, options: EmitOptions, targetFile: string): string {
  const workflows = byName(analysis.workflows);
  if (workflows.length === 0) return file('export {};');
  const imports = new Imports();
  imports.add('@norn-ts/core', 'contract');
  const blocks = workflows.map((wf) => {
    imports.add(importPath(dirname(targetFile), wf.file, options.importExtension), wf.exportName, `${wf.name}$`, true);
    return `export const ${wf.name} = contract<typeof ${wf.name}$>()(${print(contractDefinition(wf), 0, 0, true)});`;
  });
  return file(imports.print(), blocks.join('\n\n'));
}

const RESERVED = new Set(['createContainer', 'RegistryContainerOptions', 'createNornContainer', 'providers', 'options']);

export function emitContainer(analysis: Analysis, options: EmitOptions): string {
  const imports = new Imports();
  imports.add('@norn-ts/activity', 'createContainer');
  imports.add('@norn-ts/worker', 'RegistryContainerOptions', undefined, true);
  // One local name per (module, export); aliases only where names collide.
  const aliases = new Map<string, string>();
  const used = new Set(RESERVED);
  const specifierOf = (ref: DependencyRef) =>
    ref.module.kind === 'package' ? ref.module.specifier : importPath(options.outDir, ref.module.path, options.importExtension);
  const all: DependencyRef[] = [];
  const classRef = (cls: { file: string; exportName: string }): DependencyRef => ({ module: { kind: 'file', path: cls.file }, name: cls.exportName });
  const services = byClass(analysis.services);
  const activities = byClass(analysis.activities);
  for (const s of services) all.push(classRef(s), ...s.deps);
  for (const a of activities) all.push(classRef(a), ...a.deps);
  const ids = [...new Map(all.map((r) => [`${specifierOf(r)}\0${r.name}`, r])).entries()].sort(([a], [b]) => {
    const [sa, na] = a.split('\0') as [string, string];
    const [sb, nb] = b.split('\0') as [string, string];
    return compare(na, nb) || (sa.startsWith('.') ? 1 : 0) - (sb.startsWith('.') ? 1 : 0) || compare(sa, sb);
  });
  for (const [id, ref] of ids) {
    let local = ref.name;
    for (let n = 1; used.has(local); n++) local = `${ref.name}$${n}`;
    used.add(local);
    aliases.set(id, local);
    imports.add(specifierOf(ref), ref.name, local);
  }
  const local = (ref: DependencyRef) => new Code(aliases.get(`${specifierOf(ref)}\0${ref.name}`)!);
  if (options.providers) imports.add(importPath(options.outDir, options.providers, options.importExtension), 'providers');

  const entry = (cls: { file: string; exportName: string; deps: DependencyRef[] }) => ({ cls: local(classRef(cls)), deps: cls.deps.map(local) });
  const parts: string[] = [];
  if (options.providers) parts.push('providers');
  if (services.length > 0) parts.push(`services: ${print(services.map(entry), 2, 14)}`);
  if (activities.length > 0) parts.push(`activities: ${print(activities.map(entry), 2, 16)}`);
  parts.push('...options');
  const body =
    parts.length === 1
      ? `  return createContainer({ ...options });`
      : `  return createContainer({\n${parts.map((p) => `    ${p},`).join('\n')}\n  });`;
  return file(
    imports.print(),
    `/** Builds the dependency container from every @Service and @Activities class. */\nexport function createNornContainer(options: RegistryContainerOptions = {}) {\n${body}\n}`,
  );
}

export function scheduleSpecs(analysis: Analysis): Array<Omit<ScheduleModel, 'loc'>> {
  return analysis.workflows
    .flatMap((wf) => wf.schedules)
    .map(({ loc: _loc, ...spec }) => spec)
    .sort((a, b) => compare(a.id, b.id));
}

export function searchAttributes(analysis: Analysis): Record<string, string> {
  const merged: Record<string, string> = {};
  for (const wf of analysis.workflows) Object.assign(merged, wf.searchAttributes);
  return Object.fromEntries(Object.keys(merged).sort().map((k) => [k, merged[k]!]));
}

export function taskQueues(analysis: Analysis): string[] {
  return [...new Set(analysis.workflows.map((w) => w.taskQueue))].sort();
}

export function activityNames(analysis: Analysis): string[] {
  return analysis.activities.flatMap((a) => a.methods.map((m) => m.name)).sort();
}

export function emitRegistry(analysis: Analysis, options: EmitOptions): string {
  const ext = options.importExtension;
  const body = {
    workflowsPath: new Code('fileURLToPath(new URL(`./workflows${ext}`, import.meta.url))'),
    taskQueues: taskQueues(analysis),
    activities: activityNames(analysis),
    searchAttributes: searchAttributes(analysis),
    createContainer: new Code('createNornContainer'),
  };
  return file(
    [
      "import { fileURLToPath } from 'node:url';",
      "import type { NornRegistry } from '@norn-ts/worker';",
      `import { createNornContainer } from ${quote(`./container${ext}`)};`,
    ].join('\n'),
    "// `.ts` when run from source (tests, tsx), `.js` once compiled.\nconst ext = import.meta.url.endsWith('.ts') ? '.ts' : '.js';",
    `/** Everything a worker needs: pass it to createWorker({ registry }). */\nexport const registry = ${print(body, 0, 24, true)} satisfies NornRegistry;`,
  );
}

export function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}
