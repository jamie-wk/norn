import { NornConfigError, formatDuration, type Duration } from '@norn/core';
import type { WorkerDeploymentOptions } from '@temporalio/worker';
import type { NornRegistry } from './registry.js';

export type VersioningBehavior = 'pinned' | 'auto-upgrade';

export interface VersioningOptions {
  deploymentName: string;
  buildId: string;
  /** Behavior for workflows that don't set `versioning` in `@Workflow`. Default `'auto-upgrade'`. */
  defaultBehavior?: VersioningBehavior;
}

export interface WorkerConfigOptions {
  registry: NornRegistry;
  /** Subset of the registry's task queues to poll. Defaults to `NORN_TASK_QUEUES`, then all. */
  taskQueues?: readonly string[];
  /** Allow task queues no workflow declares, for activity-only workers. */
  allowUnknownTaskQueues?: boolean;
  /** Defaults to `TEMPORAL_ADDRESS`, then `localhost:7233`. */
  address?: string;
  /** Defaults to `TEMPORAL_NAMESPACE`, then `default`. */
  namespace?: string;
  /** Defaults to `TEMPORAL_API_KEY`; turns TLS on. */
  apiKey?: string;
  tls?: boolean;
  /** Worker deployment versioning. Defaults to `NORN_DEPLOYMENT_NAME` + `NORN_BUILD_ID` when both are set. */
  versioning?: VersioningOptions | false;
  /** Health server on this port (`/healthz`, `/readyz`). Defaults to `NORN_HEALTH_PORT`; off otherwise. */
  health?: { port: number; host?: string } | false;
  /** How long in-flight activities may finish after shutdown starts. Default `NORN_SHUTDOWN_GRACE`, then 30s. */
  shutdownGraceTime?: Duration;
  /** Shut down gracefully on SIGTERM and SIGINT. Default true. */
  handleSignals?: boolean;
}

export interface ResolvedWorkerConfig {
  taskQueues: string[];
  address: string;
  namespace: string;
  apiKey: string | undefined;
  tls: boolean;
  deployment: WorkerDeploymentOptions | undefined;
  healthPort: number | undefined;
  healthHost: string;
  shutdownGraceTime: string;
  handleSignals: boolean;
}

type Env = Record<string, string | undefined>;

function grace(value: Duration | string, source: string): string {
  try {
    return formatDuration(value as Duration);
  } catch (error) {
    throw new NornConfigError(`${source}: ${(error as Error).message}`, { cause: error });
  }
}

function port(value: unknown, source: string): number {
  const n = typeof value === 'string' && value.trim() !== '' ? Number(value) : value;
  if (typeof n !== 'number' || !Number.isInteger(n) || n < 0 || n > 65_535) {
    throw new NornConfigError(`${source} must be a port number between 0 and 65535, got ${JSON.stringify(value)}`);
  }
  return n;
}

/** Resolves worker settings from options, then environment variables, then defaults. */
export function resolveWorkerConfig(options: WorkerConfigOptions, env: Env = process.env): ResolvedWorkerConfig {
  const { registry } = options;
  if (!registry || !Array.isArray(registry.taskQueues) || typeof registry.createContainer !== 'function') {
    throw new NornConfigError('createWorker() needs the registry generated by `norn gen` (.norn/registry.ts)');
  }

  const fromEnv = env.NORN_TASK_QUEUES?.split(',').map((q) => q.trim()).filter(Boolean);
  const taskQueues = [...(options.taskQueues ?? (fromEnv?.length ? fromEnv : registry.taskQueues))];
  if (taskQueues.length === 0) throw new NornConfigError('A worker needs at least one task queue');
  if (!options.allowUnknownTaskQueues) {
    for (const queue of taskQueues) {
      if (!registry.taskQueues.includes(queue)) {
        throw new NornConfigError(
          `Task queue ${queue} is not used by any workflow (known: ${registry.taskQueues.join(', ')}). ` +
            'Pass allowUnknownTaskQueues: true for activity-only workers',
        );
      }
    }
  }

  let deployment: WorkerDeploymentOptions | undefined;
  const versioning =
    options.versioning === false
      ? undefined
      : (options.versioning ??
        (env.NORN_DEPLOYMENT_NAME || env.NORN_BUILD_ID
          ? { deploymentName: env.NORN_DEPLOYMENT_NAME ?? '', buildId: env.NORN_BUILD_ID ?? '' }
          : undefined));
  if (versioning) {
    if (!versioning.deploymentName) throw new NornConfigError('Worker versioning needs a deployment name (NORN_DEPLOYMENT_NAME)');
    if (!versioning.buildId) throw new NornConfigError('Worker versioning needs a build ID (NORN_BUILD_ID)');
    const behavior = versioning.defaultBehavior ?? 'auto-upgrade';
    if (behavior !== 'pinned' && behavior !== 'auto-upgrade') {
      throw new NornConfigError(`versioning.defaultBehavior must be 'pinned' or 'auto-upgrade'`);
    }
    deployment = {
      version: { deploymentName: versioning.deploymentName, buildId: versioning.buildId },
      useWorkerVersioning: true,
      defaultVersioningBehavior: behavior === 'pinned' ? 'PINNED' : 'AUTO_UPGRADE',
    };
  }

  const health = options.health === false ? undefined : options.health;
  const healthPort =
    health !== undefined
      ? port(health.port, 'health.port')
      : env.NORN_HEALTH_PORT && options.health !== false
        ? port(env.NORN_HEALTH_PORT, 'NORN_HEALTH_PORT')
        : undefined;

  const apiKey = options.apiKey ?? (env.TEMPORAL_API_KEY || undefined);
  return {
    taskQueues,
    // Empty variables count as unset (as in the CLI), e.g. from `${VAR:-}` in compose files.
    address: options.address ?? (env.TEMPORAL_ADDRESS || 'localhost:7233'),
    namespace: options.namespace ?? (env.TEMPORAL_NAMESPACE || 'default'),
    apiKey,
    tls: options.tls ?? (apiKey !== undefined || env.TEMPORAL_TLS === 'true'),
    deployment,
    healthPort,
    healthHost: (health && health.host) ?? '0.0.0.0',
    shutdownGraceTime:
      options.shutdownGraceTime !== undefined
        ? grace(options.shutdownGraceTime, 'shutdownGraceTime')
        : env.NORN_SHUTDOWN_GRACE
          ? grace(env.NORN_SHUTDOWN_GRACE, 'NORN_SHUTDOWN_GRACE')
          : '30000ms',
    handleSignals: options.handleSignals ?? true,
  };
}
