import type { SearchAttributeType } from '@norn/core';
import type { Container, ErrorMappingOptions, InjectionKey } from '@norn/activity';

export type ScheduleOverlap = 'skip' | 'buffer-one' | 'buffer-all' | 'cancel-other' | 'terminate-other' | 'allow-all';

/** A schedule declared with `@Schedule`, as written to `.norn/schedules.json`. */
export interface ScheduleSpec {
  id: string;
  workflowType: string;
  taskQueue: string;
  cron: readonly string[];
  input?: unknown;
  overlap?: ScheduleOverlap;
  timeZone?: string;
  pauseOnFailure?: boolean;
  paused?: boolean;
  note?: string;
}

export interface RegistryContainerOptions {
  overrides?: ReadonlyArray<readonly [InjectionKey, unknown]>;
  errors?: ErrorMappingOptions;
}

/**
 * Everything a worker needs, generated by `norn gen` into `.norn/registry.ts`. The worker reads
 * task queues and the workflow bundle entry from here and builds activities from the container.
 */
export interface NornRegistry {
  /** Absolute path of the generated workflows barrel (`.ts` in development, `.js` once compiled). */
  workflowsPath: string;
  /** Every task queue a workflow in this project is declared on. */
  taskQueues: readonly string[];
  /** Registered activity names, including prefixes. */
  activities: readonly string[];
  searchAttributes: Readonly<Record<string, SearchAttributeType>>;
  createContainer(options?: RegistryContainerOptions): Container;
}

/** Identity helper with type checking, for hand-written registries. */
export function defineRegistry(registry: NornRegistry): NornRegistry {
  return registry;
}
