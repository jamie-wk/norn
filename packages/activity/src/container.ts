import { AsyncLocalStorage } from 'node:async_hooks';
import { Context, type Info } from '@temporalio/activity';
import { NornConfigError } from '@norn/core';
import { describeActivities, describeService, type ActivitiesDefinition, type Scope } from './decorators.js';
import { mapActivityError, validateErrorOptions, type ErrorMappingOptions } from './errors.js';
import { keyName, isInjectionKey, type InjectionKey, type Resolved } from './tokens.js';

type AnyClass = abstract new (...args: any[]) => unknown;
type ConcreteClass = new (...args: any[]) => unknown;

export interface ProviderContext {
  /** The running activity, for activity-scoped providers. */
  activity?: Info;
  /** Resolves another dependency. Prefer `deps`, which the container can check up front. */
  resolve<K extends InjectionKey>(key: K): Promise<Resolved<K>>;
}

export interface ProviderOptions<T> {
  /** `'singleton'` (default) or `'activity'` for a fresh value per activity execution. */
  scope?: Scope;
  /** Dependencies resolved before the factory runs and passed after the context argument. */
  deps?: readonly InjectionKey[];
  /** Cleans the value up when its scope ends. Defaults to `Symbol.asyncDispose` / `Symbol.dispose`. */
  dispose?: (value: T) => unknown;
}

export interface Provider<T = unknown> {
  readonly kind: 'norn.provider';
  readonly key: InjectionKey<T>;
  readonly factory: (ctx: ProviderContext, ...deps: any[]) => T | Promise<T>;
  readonly scope: Scope;
  readonly deps: readonly InjectionKey[];
  readonly dispose: ((value: T) => unknown) | undefined;
}

/** Registers a factory for a token or class: database pools, SDK clients, configuration. */
export function provide<K extends InjectionKey>(
  key: K,
  factory: (ctx: ProviderContext, ...deps: any[]) => Resolved<K> | Promise<Resolved<K>>,
  options: ProviderOptions<Resolved<K>> = {},
): Provider<Resolved<K>> {
  if (!isInjectionKey(key)) throw new NornConfigError('provide(): the first argument must be a class or token');
  if (typeof factory !== 'function') throw new NornConfigError(`provide(${keyName(key)}): factory must be a function`);
  if (options.scope !== undefined && options.scope !== 'singleton' && options.scope !== 'activity') {
    throw new NornConfigError(`provide(${keyName(key)}): scope must be 'singleton' or 'activity'`);
  }
  const deps = options.deps ?? [];
  if (!Array.isArray(deps) || deps.some((d) => !isInjectionKey(d))) {
    throw new NornConfigError(`provide(${keyName(key)}): deps must list classes or tokens`);
  }
  return Object.freeze({
    kind: 'norn.provider' as const,
    key: key as InjectionKey<Resolved<K>>,
    factory,
    scope: options.scope ?? 'singleton',
    deps,
    dispose: options.dispose,
  });
}

export interface ClassEntry {
  cls: AnyClass;
  /** Constructor dependencies in parameter order. Generated by `norn gen`; overrides `inject`. */
  deps?: readonly InjectionKey[];
}

export interface ContainerOptions {
  providers?: readonly Provider<any>[];
  services?: readonly ClassEntry[];
  activities?: readonly ClassEntry[];
  /** Replace any dependency with a fixed value, typically in tests. Overrides are never disposed. */
  overrides?: ReadonlyArray<readonly [InjectionKey, unknown]>;
  errors?: ErrorMappingOptions;
}

export type ActivityFunction = (...args: any[]) => Promise<unknown>;

export interface Container extends AsyncDisposable {
  /** Resolves a singleton dependency, creating it and its dependencies on first use. */
  resolve<K extends InjectionKey>(key: K): Promise<Resolved<K>>;
  /** Creates every singleton activity class and returns the worker's activity map, keyed by name. */
  activities(): Promise<Record<string, ActivityFunction>>;
  /** The activity classes registered with this container. */
  readonly definitions: readonly ActivitiesDefinition[];
}

interface Node {
  key: InjectionKey;
  label: string;
  /** Declared scope; activity classes are upgraded to 'activity' when they need scoped values. */
  scope: Scope;
  deps: readonly InjectionKey[];
  create: (ctx: ProviderContext, deps: unknown[]) => unknown;
  dispose: ((value: any) => unknown) | undefined;
  /** Supplied values (overrides) are owned by the caller. */
  owned: boolean;
}

interface ScopeState {
  info: Info;
  values: Map<InjectionKey, Promise<unknown>>;
  created: Array<{ node: Node; value: unknown }>;
}

async function disposeValue(node: Node, value: unknown): Promise<void> {
  if (!node.owned) return;
  if (node.dispose) {
    await node.dispose(value);
    return;
  }
  if (value !== null && (typeof value === 'object' || typeof value === 'function')) {
    const v = value as Partial<AsyncDisposable & Disposable>;
    if (typeof v[Symbol.asyncDispose] === 'function') await v[Symbol.asyncDispose]!();
    else if (typeof v[Symbol.dispose] === 'function') v[Symbol.dispose]!();
  }
}

async function disposeAll(created: Array<{ node: Node; value: unknown }>): Promise<void> {
  const errors: unknown[] = [];
  for (const { node, value } of created.toReversed()) {
    try {
      await disposeValue(node, value);
    } catch (error) {
      errors.push(error);
    }
  }
  created.length = 0;
  if (errors.length === 1) throw errors[0];
  if (errors.length > 1) throw new AggregateError(errors, 'Several dependencies failed to dispose');
}

function classNode(entry: ClassEntry, scope: Scope, key: InjectionKey, label: string, inject: readonly InjectionKey[] | undefined): Node {
  const deps = entry.deps ?? inject ?? [];
  if (!Array.isArray(deps) || deps.some((d) => !isInjectionKey(d))) {
    throw new NornConfigError(`${label}: deps must list classes or tokens`);
  }
  if (entry.cls.length > deps.length) {
    throw new NornConfigError(
      `${label} takes ${entry.cls.length} constructor arguments but only ${deps.length} dependencies are known. ` +
        `Run \`norn gen\` or list them with inject: [...]`,
    );
  }
  return {
    key,
    label,
    scope,
    deps,
    create: (_ctx, values) => new (entry.cls as ConcreteClass)(...values),
    dispose: undefined,
    owned: true,
  };
}

/**
 * Builds the dependency container for a worker. `norn gen` writes this call for you from your
 * `@Service` and `@Activities` classes; you can also call it directly, for example in tests.
 */
export function createContainer(options: ContainerOptions = {}): Container {
  validateErrorOptions(options.errors);
  const errorOptions = options.errors ?? {};
  const nodes = new Map<InjectionKey, Node>();
  const add = (node: Node): void => {
    if (nodes.has(node.key)) throw new NornConfigError(`There is more than one provider for ${keyName(node.key)}`);
    nodes.set(node.key, node);
  };

  for (const provider of options.providers ?? []) {
    if (provider?.kind !== 'norn.provider') throw new NornConfigError('providers must be created with provide()');
    add({
      key: provider.key,
      label: keyName(provider.key),
      scope: provider.scope,
      deps: provider.deps,
      create: (ctx, values) => provider.factory(ctx, ...values),
      dispose: provider.dispose,
      owned: true,
    });
  }
  for (const entry of options.services ?? []) {
    const def = describeService(entry.cls);
    add(classNode(entry, def.scope, def.provides, def.className, def.inject));
  }

  const definitions: ActivitiesDefinition[] = [];
  const activityClassList: Array<{ cls: AnyClass; def: ActivitiesDefinition }> = [];
  const activityOwners = new Map<string, string>();
  for (const entry of options.activities ?? []) {
    const def = describeActivities(entry.cls);
    for (const method of def.methods) {
      const owner = activityOwners.get(method.name);
      if (owner) throw new NornConfigError(`Activity "${method.name}" is registered by both ${owner} and ${def.className}`);
      activityOwners.set(method.name, def.className);
    }
    definitions.push(def);
    activityClassList.push({ cls: entry.cls, def });
    add(classNode(entry, 'singleton', entry.cls, def.className, def.inject));
  }

  for (const [key, value] of options.overrides ?? []) {
    if (!isInjectionKey(key)) throw new NornConfigError('overrides must be [classOrToken, value] pairs');
    nodes.set(key, {
      key,
      label: keyName(key),
      scope: 'singleton',
      deps: [],
      create: () => value,
      dispose: undefined,
      owned: false,
    });
  }

  // Cycles are reported before anything is created.
  const state = new Map<InjectionKey, 'visiting' | 'done'>();
  const visit = (key: InjectionKey, path: InjectionKey[]): void => {
    const node = nodes.get(key);
    if (!node || state.get(key) === 'done') return;
    if (state.get(key) === 'visiting') {
      const cycle = [...path.slice(path.indexOf(key)), key].map(keyName).join(' -> ');
      throw new NornConfigError(`Dependency cycle: ${cycle}`);
    }
    state.set(key, 'visiting');
    for (const dep of node.deps) visit(dep, [...path, key]);
    state.set(key, 'done');
  };
  for (const key of nodes.keys()) visit(key, []);

  // Effective scope: activity classes follow their dependencies; singletons must not capture
  // activity-scoped values, because they would keep the first execution's value forever.
  const activityClasses = new Set<InjectionKey>(activityClassList.map((e) => e.cls));
  const effective = new Map<InjectionKey, Scope>();
  const scopeOf = (key: InjectionKey): Scope => {
    const known = effective.get(key);
    if (known) return known;
    const node = nodes.get(key);
    if (!node) return 'singleton';
    let scope: Scope = node.scope;
    for (const dep of node.deps) {
      if (scopeOf(dep) !== 'activity' || scope === 'activity') continue;
      if (activityClasses.has(key)) {
        scope = 'activity';
        continue;
      }
      throw new NornConfigError(
        `${node.label} is a singleton but depends on activity-scoped ${keyName(dep)}. ` +
          `Make ${node.label} activity-scoped, or inject a factory instead`,
      );
    }
    effective.set(key, scope);
    return scope;
  };
  for (const key of nodes.keys()) scopeOf(key);

  const singletons = new Map<InjectionKey, Promise<unknown>>();
  const created: Array<{ node: Node; value: unknown }> = [];
  const activityScope = new AsyncLocalStorage<ScopeState>();
  let disposed = false;

  const resolveKey = (key: InjectionKey, path: readonly InjectionKey[], scope: ScopeState | undefined): Promise<unknown> => {
    if (disposed) return Promise.reject(new NornConfigError('The container has been disposed'));
    // Factories can resolve through ctx.resolve, which the startup cycle check can't see.
    if (path.includes(key)) return Promise.reject(new NornConfigError(`Dependency cycle: ${[...path, key].map(keyName).join(' -> ')}`));
    const node = nodes.get(key);
    if (!node) {
      const chain = [...path, key].map(keyName).join(' -> ');
      const needer = path.length ? `, required by ${keyName(path.at(-1))}` : '';
      return Promise.reject(
        new NornConfigError(`No provider for ${keyName(key)}${needer} (path: ${chain}). Register it with provide() or @Service`),
      );
    }
    const isScoped = effective.get(key) === 'activity';
    if (isScoped && !scope) {
      return Promise.reject(new NornConfigError(`${node.label} is activity-scoped and can only be resolved while an activity runs`));
    }
    const cache = isScoped ? scope!.values : singletons;
    const cached = cache.get(key);
    if (cached) return cached;
    const promise = (async () => {
      const deps: unknown[] = [];
      for (const dep of node.deps) deps.push(await resolveKey(dep, [...path, key], scope));
      const ctx: ProviderContext = {
        activity: scope?.info,
        resolve: (k) => resolveKey(k, [...path, key], scope) as Promise<any>,
      };
      const value = await node.create(ctx, deps);
      (isScoped ? scope!.created : created).push({ node, value });
      return value;
    })();
    cache.set(key, promise);
    // A failed creation can be retried by the next activity attempt.
    promise.catch(() => {
      if (cache.get(key) === promise) cache.delete(key);
    });
    return promise;
  };

  const resolveActivityKey = (key: InjectionKey): Promise<unknown> => resolveKey(key, [], activityScope.getStore());

  let activityMap: Promise<Record<string, ActivityFunction>> | undefined;
  const buildActivities = async (): Promise<Record<string, ActivityFunction>> => {
    // Create every singleton up front so configuration problems fail the worker at startup.
    for (const [key, scope] of effective) {
      if (scope === 'singleton' && nodes.has(key)) await resolveKey(key, [], undefined);
    }
    const map: Record<string, ActivityFunction> = {};
    for (const { cls, def } of activityClassList) {
      for (const method of def.methods) {
        const activity = async (...args: unknown[]): Promise<unknown> => {
          const info = Context.current().info;
          const scope: ScopeState = { info, values: new Map(), created: [] };
          return activityScope.run(scope, async () => {
            try {
              let instance: Record<string, (...a: unknown[]) => unknown>;
              try {
                instance = (await resolveActivityKey(cls)) as typeof instance;
              } catch (error) {
                throw mapActivityError(error, info.activityType, undefined, errorOptions);
              }
              try {
                return await instance[method.method]!(...args);
              } catch (error) {
                throw mapActivityError(error, info.activityType, method.nonRetryable, errorOptions);
              }
            } finally {
              try {
                await disposeAll(scope.created);
              } catch (error) {
                // The activity already ran: a failed cleanup must not turn its outcome into a retry.
                const errors = error instanceof AggregateError ? error.errors.map(String) : [String(error)];
                Context.current().log.warn('Disposing activity-scoped values failed', { activityType: info.activityType, errors });
              }
            }
          });
        };
        Object.defineProperty(activity, 'name', { value: method.name });
        map[method.name] = activity;
      }
    }
    return map;
  };

  return {
    definitions,
    resolve: <K extends InjectionKey>(key: K) => resolveActivityKey(key) as Promise<Resolved<K>>,
    activities: () => {
      if (disposed) return Promise.reject(new NornConfigError('The container has been disposed'));
      activityMap ??= buildActivities();
      activityMap.catch(() => (activityMap = undefined));
      return activityMap;
    },
    async [Symbol.asyncDispose]() {
      if (disposed) return;
      disposed = true;
      await Promise.allSettled(singletons.values());
      await disposeAll(created);
    },
  };
}
